# อธิบาย: ประกาศฟังก์ชัน load_sample_data: อ่าน CSV ตัวอย่าง ตรวจคอลัมน์/ข้อมูลซ้ำ/ราคา แล้วคืน list ของ records
def load_sample_data(sample_path, ticker="AAPL"):
    """อ่านราคาหุ้นจากไฟล์ CSV ตัวอย่าง และเลือกเฉพาะหุ้นที่ต้องการ"""
    # อธิบาย: กำหนดค่าให้ตัวแปร `records`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
    records = []
    # อธิบาย: กำหนดค่าให้ตัวแปร `seen_dates`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
    seen_dates = set()
    # อธิบาย: เริ่มบล็อกที่อาจเกิดข้อผิดพลาด เพื่อให้ except จัดการได้
    try:
        # อธิบาย: เปิดทรัพยากรด้วย context manager และปิด/จัดการให้อัตโนมัติเมื่อออกจากบล็อก
        with open(sample_path, "r", newline="", encoding="utf-8") as file:
            # อธิบาย: กำหนดค่าให้ตัวแปร `reader`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
            reader = csv.DictReader(file)
            # อธิบาย: กำหนดค่าให้ตัวแปร `required`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
            required = {"date", "ticker", "close"}
            # อธิบาย: ตรวจเงื่อนไขนี้ก่อนเลือกว่าจะทำบล็อกคำสั่งด้านล่างหรือไม่
            if not reader.fieldnames or not required.issubset(reader.fieldnames):
                # อธิบาย: หยุดการทำงานของฟังก์ชัน ณ จุดนี้และส่ง exception ให้ผู้เรียกจัดการ
                raise ValueError("ไฟล์ CSV ต้องมีคอลัมน์ date, ticker และ close")

            # อธิบาย: เริ่มวนซ้ำ โดยนำสมาชิกแต่ละตัวจากชุดข้อมูลมาใส่ตัวแปรหน้าคำว่า in
            for row_number, row in enumerate(reader, start=2):
                # อธิบาย: ตรวจเงื่อนไขนี้ก่อนเลือกว่าจะทำบล็อกคำสั่งด้านล่างหรือไม่
                if (row.get("ticker") or "").strip().upper() != ticker.upper():
                    # อธิบาย: ข้ามคำสั่งที่เหลือในรอบปัจจุบัน แล้วเริ่มรอบ loop ถัดไป
                    continue
                # อธิบาย: เริ่มบล็อกที่อาจเกิดข้อผิดพลาด เพื่อให้ except จัดการได้
                try:
                    # อธิบาย: กำหนดค่าให้ตัวแปร `date`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
                    date = row["date"].strip()
                    # อธิบาย: กำหนดค่าให้ตัวแปร `close`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
                    close = float(row["close"])
                    # อธิบาย: ตรวจเงื่อนไขนี้ก่อนเลือกว่าจะทำบล็อกคำสั่งด้านล่างหรือไม่
                    if not math.isfinite(close) or close <= 0:
                        # อธิบาย: หยุดการทำงานของฟังก์ชัน ณ จุดนี้และส่ง exception ให้ผู้เรียกจัดการ
                        raise ValueError
                # อธิบาย: กำหนดวิธีรับมือเมื่อเกิดข้อผิดพลาดชนิดที่ระบุ
                except (ValueError, TypeError, AttributeError):
                    # อธิบาย: แสดงข้อความหรือค่าบน Terminal เพื่อสื่อสารกับผู้ใช้/ตรวจสอบผล
                    print(f"ข้ามแถวที่ {row_number} เพราะข้อมูลไม่ถูกต้อง")
                    # อธิบาย: ข้ามคำสั่งที่เหลือในรอบปัจจุบัน แล้วเริ่มรอบ loop ถัดไป
                    continue
                # อธิบาย: ตรวจเงื่อนไขนี้ก่อนเลือกว่าจะทำบล็อกคำสั่งด้านล่างหรือไม่
                if date in seen_dates:
                    # อธิบาย: ข้ามคำสั่งที่เหลือในรอบปัจจุบัน แล้วเริ่มรอบ loop ถัดไป
                    continue
                # อธิบาย: เพิ่มสมาชิกเข้า set; set จะเก็บค่าไม่ซ้ำ
                seen_dates.add(date)
                # อธิบาย: เพิ่มสมาชิกหนึ่งตัวต่อท้าย list ที่ระบุ
                records.append({"date": date, "ticker": ticker.upper(), "close": close})
    # อธิบาย: กำหนดวิธีรับมือเมื่อเกิดข้อผิดพลาดชนิดที่ระบุ
    except FileNotFoundError:
        # อธิบาย: แสดงข้อความหรือค่าบน Terminal เพื่อสื่อสารกับผู้ใช้/ตรวจสอบผล
        print("ไม่พบไฟล์ข้อมูลตัวอย่าง:", sample_path)
        # อธิบาย: ส่งค่ากลับไปยังจุดที่เรียกฟังก์ชันนี้; ผู้เรียกสามารถเก็บผลไปใช้ต่อได้
        return []
    # อธิบาย: กำหนดวิธีรับมือเมื่อเกิดข้อผิดพลาดชนิดที่ระบุ
    except (OSError, csv.Error, ValueError) as error:
        # อธิบาย: แสดงข้อความหรือค่าบน Terminal เพื่อสื่อสารกับผู้ใช้/ตรวจสอบผล
        print("อ่านไฟล์ข้อมูลตัวอย่างไม่ได้:", error)
        # อธิบาย: ส่งค่ากลับไปยังจุดที่เรียกฟังก์ชันนี้; ผู้เรียกสามารถเก็บผลไปใช้ต่อได้
        return []

    # อธิบาย: เรียงสมาชิกใน list เดิม (in-place) ไม่ได้สร้าง list ใหม่
    records.sort(key=lambda item: item["date"])
    # อธิบาย: ส่งค่ากลับไปยังจุดที่เรียกฟังก์ชันนี้; ผู้เรียกสามารถเก็บผลไปใช้ต่อได้
    return records


