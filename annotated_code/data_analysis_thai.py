# อธิบาย: ประกาศฟังก์ชัน calculate_daily_returns: แปลง list ราคาปิดเป็น list ผลตอบแทนรายวันด้วยสูตร (วันนี้/วันก่อน)-1
def calculate_daily_returns(prices):
    """
    คำนวณผลตอบแทนรายวันจากราคาปิดหุ้น

    สูตร:
    Daily Return = (ราคาวันนี้ / ราคาวันก่อน) - 1
    """

    # ตรวจสอบว่าข้อมูลเป็น list หรือ tuple
    # อธิบาย: ตรวจเงื่อนไขนี้ก่อนเลือกว่าจะทำบล็อกคำสั่งด้านล่างหรือไม่
    if not isinstance(prices, (list, tuple)):
        # อธิบาย: หยุดการทำงานของฟังก์ชัน ณ จุดนี้และส่ง exception ให้ผู้เรียกจัดการ
        raise ValueError("Prices must be a list or tuple.")

    # อธิบาย: กำหนดค่าให้ตัวแปร `numeric_prices`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
    numeric_prices = []

    # แปลงราคาทุกตัวเป็น float
    # อธิบาย: เริ่มวนซ้ำ โดยนำสมาชิกแต่ละตัวจากชุดข้อมูลมาใส่ตัวแปรหน้าคำว่า in
    for price in prices:

        # ป้องกัน Boolean ซึ่ง Python มองว่าเป็นตัวเลขได้
        # อธิบาย: ตรวจเงื่อนไขนี้ก่อนเลือกว่าจะทำบล็อกคำสั่งด้านล่างหรือไม่
        if isinstance(price, bool):
            # อธิบาย: หยุดการทำงานของฟังก์ชัน ณ จุดนี้และส่ง exception ให้ผู้เรียกจัดการ
            raise ValueError("Prices must be numeric values.")

        # อธิบาย: เริ่มบล็อกที่อาจเกิดข้อผิดพลาด เพื่อให้ except จัดการได้
        try:
            # อธิบาย: กำหนดค่าให้ตัวแปร `numeric_price`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
            numeric_price = float(price)

        # อธิบาย: กำหนดวิธีรับมือเมื่อเกิดข้อผิดพลาดชนิดที่ระบุ
        except (TypeError, ValueError) as error:
            # อธิบาย: หยุดการทำงานของฟังก์ชัน ณ จุดนี้และส่ง exception ให้ผู้เรียกจัดการ
            raise ValueError(
                # อธิบาย: เป็นข้อความ literal ที่ถูกใส่เป็นสมาชิก/argument ในโครงสร้างข้อมูลด้านบน
                "Prices must all be numeric."
            # อธิบาย: ปิดวงเล็บของ expression หรือคำสั่งหลายบรรทัดที่เริ่มไว้ก่อนหน้า
            ) from error

        # ราคาต้องเป็นตัวเลขที่มีค่าจำกัดและมากกว่า 0
        # อธิบาย: ตรวจเงื่อนไขนี้ก่อนเลือกว่าจะทำบล็อกคำสั่งด้านล่างหรือไม่
        if not math.isfinite(numeric_price) or numeric_price <= 0:
            # อธิบาย: หยุดการทำงานของฟังก์ชัน ณ จุดนี้และส่ง exception ให้ผู้เรียกจัดการ
            raise ValueError(
                # อธิบาย: เป็นข้อความ literal ที่ถูกใส่เป็นสมาชิก/argument ในโครงสร้างข้อมูลด้านบน
                "Prices must be finite numbers greater than zero."
            # อธิบาย: ปิดวงเล็บของ expression หรือคำสั่งหลายบรรทัดที่เริ่มไว้ก่อนหน้า
            )

        # อธิบาย: เพิ่มสมาชิกหนึ่งตัวต่อท้าย list ที่ระบุ
        numeric_prices.append(numeric_price)

    # ต้องมีราคาอย่างน้อย 2 วันจึงจะคำนวณผลตอบแทนได้
    # อธิบาย: ตรวจเงื่อนไขนี้ก่อนเลือกว่าจะทำบล็อกคำสั่งด้านล่างหรือไม่
    if len(numeric_prices) < 2:
        # อธิบาย: ส่งค่ากลับไปยังจุดที่เรียกฟังก์ชันนี้; ผู้เรียกสามารถเก็บผลไปใช้ต่อได้
        return []

    # อธิบาย: กำหนดค่าให้ตัวแปร `daily_returns`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
    daily_returns = []

    # คำนวณผลตอบแทนระหว่างวัน
    # อธิบาย: เริ่มวนซ้ำ โดยนำสมาชิกแต่ละตัวจากชุดข้อมูลมาใส่ตัวแปรหน้าคำว่า in
    for index in range(1, len(numeric_prices)):

        # อธิบาย: กำหนดค่าให้ตัวแปร `previous_price`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
        previous_price = numeric_prices[index - 1]
        # อธิบาย: กำหนดค่าให้ตัวแปร `current_price`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
        current_price = numeric_prices[index]

        # อธิบาย: กำหนดค่าให้ตัวแปร `daily_return`; ค่าที่ได้จะถูกนำไปใช้ในคำสั่งถัดไป
        daily_return = (current_price / previous_price) - 1

        # อธิบาย: เพิ่มสมาชิกหนึ่งตัวต่อท้าย list ที่ระบุ
        daily_returns.append(daily_return)

    # อธิบาย: ส่งค่ากลับไปยังจุดที่เรียกฟังก์ชันนี้; ผู้เรียกสามารถเก็บผลไปใช้ต่อได้
    return daily_returns


